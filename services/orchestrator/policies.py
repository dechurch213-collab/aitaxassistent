# --- детекторы ---

SIMPLE_EXPLAIN_RE = re.compile(
    r"(объясни\s+проще|понятнее|простыми\s+словами|я\s+не\s+понял|не\s+понятно|"
    r"қарапайым|түсінбедім|анық\s+айт|қарапайым\s+тілмен)",
    re.IGNORECASE,
)

QUESTION_WORDS = (
    "сколько", "как", "какой", "какая", "какое", "какие", "нужно", "можно",
    "надо", "ли ", "где", "когда", "почему", "за что",
    "қанша", "қалай", "қайда", "қашан", "неге", "мүмкін", "керек",
)


def is_simple_explain_request(text: str) -> bool:
    return bool(SIMPLE_EXPLAIN_RE.search(text or ""))


def is_substantive_question(text: str) -> bool:
    """Существенный вопрос (новый запрос) vs. реакция/подтверждение."""
    t = (text or "").lower().strip()
    if not t or len(t) < 8:
        return False
    if "?" in t:
        return True
    if t in ("да", "нет", "хорошо", "спасибо", "ок", "жақсы", "рақмет", "иә", "жоқ"):
        return False
    return any(w in t for w in QUESTION_WORDS)


def is_policy_dispute(text: str, keywords: list) -> bool:
    t = (text or "").lower()
    return any(k.lower() in t for k in (keywords or []))


def pick_filler(lang: str, cfg: dict) -> str:
    fillers = cfg.get("fillers", {}).get(lang, cfg.get("fillers", {}).get("ru", ["Одно мгновение."]))
    return random.choice(fillers)


def build_system_prompt(lang: str, elder_mode: bool, simplify: bool, fix_citations: list | None) -> str:
    base = SYSTEM_PROMPT_KK if lang == "kk" else SYSTEM_PROMPT_RU
    extra = []
    if elder_mode:
        extra.append(
            "Звонящий — пожилой человек или говорит неясно. Отвечай ОЧЕНЬ простыми словами, "
            "короткими предложениями, без терминов, если возможно."
        )
    if simplify:
        extra.append(
            "Звонящий попросил объяснить проще: перескажи предыдущий ответ максимально "
            "простыми словами, по возможности с бытовым примером."
        )
    if fix_citations:
        extra.append(
            "ВНИМАНИЕ: цитируй ТОЛЬКО эти номера статей: " + ", ".join(fix_citations)
            + ". Другие номера использовать запрещено."
        )
    if extra:
        base += "\n\nДополнительно: " + " ".join(extra)
    return base
